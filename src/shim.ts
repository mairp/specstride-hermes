/**
 * The shim of the Hermes host (T014, contracts/150-host-hermes/shim.md,
 * research R6): the text of `bin/specstride-hermes.mjs`, rendered at build
 * time as a STANDALONE file. The shipped script imports three modules of
 * Node and nothing else; it fetches, installs and updates nothing.
 *
 * Resolution (F150-FR-011): `SPECSTRIDE_BIN`, then the first `specstride` on
 * `PATH` with the shim's own directory excluded, else exit 127 with one line
 * naming the engine's documented install command. Protocol (F150-FR-012):
 * the integer `--protocol` prints must sit in the range of
 * `package.json#specstride.protocol`; a mismatch prints the one refusal line
 * and exits 4; a differing package version alone never refuses. Every other
 * exit code of the CLI passes through unchanged.
 *
 * Gateway-cgroup escape (F150-FR-013, host fact HF-GW-UNIT): for `launch`
 * and `resume` only, when the cgroup file names `hermes-gateway.service`,
 * the CLI is re-executed under
 * `systemd-run --scope --collect --quiet --unit=specstride-<8hex>`
 * (`--user` when the uid is not 0). A missing `systemd-run`, or a `--user`
 * failure because no user manager or D-Bus is reachable, prints the one
 * `[SPECSTRIDE-WARN]` line and runs the CLI directly. `status` is never
 * wrapped.
 *
 * Watch list (F150-FR-014): on a `launch` that exits 0, the absolute working
 * directory is appended to `$HERMES_HOME/specstride-host/watch.json`,
 * atomically, with set semantics. The cgroup file's path is overridable by
 * `SPECSTRIDE_CGROUP_FILE` so a test can feed a fixture.
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The only name the built shim may carry; the build refuses anything else. */
export const SHIM_FILE_NAME = "specstride-hermes";

/** The unit of the Hermes gateway, host fact HF-GW-UNIT (verified row). */
export const GATEWAY_UNIT = "hermes-gateway.service";

/** The actions the gateway-cgroup escape wraps; nothing else. */
export const WRAPPED_ACTIONS: readonly string[] = Object.freeze(["launch", "resume"]);

/** The file the cgroup probe reads; `SPECSTRIDE_CGROUP_FILE` overrides it. */
export const CGROUP_FILE = "/proc/self/cgroup";

/**
 * The build-time refusal of a wrong shim name: the shim is
 * `specstride-hermes`, never `specstride` (contracts/shim.md, F150-FR-014).
 */
export function assertShimFileName(name: string): string {
  if (name !== SHIM_FILE_NAME) {
    throw new Error(
      `the shim of this host is named ${SHIM_FILE_NAME}; ${JSON.stringify(name)} would install or link it as the engine's own executable`,
    );
  }
  return name;
}

/** The protocol range this package supports, read from the manifest. */
export type ProtocolRange = { readonly min: number; readonly max: number };

/** Read `package.json#specstride.protocol` from a package root. */
export function protocolRangeOfPackage(packageRoot: string): ProtocolRange {
  const manifest = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8")) as {
    specstride?: { protocol?: { min?: number; max?: number } };
  };
  const protocol = manifest.specstride?.protocol;
  if (!protocol || typeof protocol.min !== "number" || typeof protocol.max !== "number") {
    throw new Error("package.json carries no specstride.protocol range");
  }
  return { min: protocol.min, max: protocol.max };
}

const HERE = dirname(fileURLToPath(import.meta.url));

/** The protocol range of THIS package, read once at load. */
export function thisPackageProtocolRange(): ProtocolRange {
  return protocolRangeOfPackage(join(HERE, ".."));
}

/**
 * The standalone shim script. Every constant and every line it prints is
 * interpolated from this module, so the shipped file cannot drift from the
 * contract; the generated text holds no template literal of its own.
 */
export function hermesShimScript(options?: { readonly protocol?: ProtocolRange }): string {
  const protocol = options?.protocol ?? thisPackageProtocolRange();
  const installCommand = "npm install -g specstride@0.0.0";
  const lines: string[] = [
    "#!/usr/bin/env node",
    "//",
    "// Generated by @specstride/host-hermes (src/shim.ts) at build time — edit the",
    "// generator, never this file. Hermes host of Specstride; the one channel to",
    "// the CLI for skills, plugin glue and the watcher. Resolution: SPECSTRIDE_BIN,",
    "// then PATH with this shim's own directory excluded; nothing is fetched,",
    "// installed or updated.",
    "//",
    'import { accessSync, constants, mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";',
    'import { spawnSync } from "node:child_process";',
    'import { randomBytes } from "node:crypto";',
    'import { dirname, join, resolve } from "node:path";',
    'import { fileURLToPath } from "node:url";',
    "",
    'const EXECUTABLE_VARIABLE = "SPECSTRIDE_BIN";',
    'const CGROUP_VARIABLE = "SPECSTRIDE_CGROUP_FILE";',
    'const EXECUTABLE_NAME = "specstride";',
    'const PROTOCOL_FLAG = "--protocol";',
    "const PROTOCOL_MIN = " + JSON.stringify(protocol.min) + ";",
    "const PROTOCOL_MAX = " + JSON.stringify(protocol.max) + ";",
    'const REFUSAL_LINE = "[SPECSTRIDE-REFUSE] action=protocol reason=protocol-mismatch";',
    'const WARN_LINE = "[SPECSTRIDE-WARN] action=launch reason=gateway-cgroup";',
    'const GATEWAY_UNIT = ' + JSON.stringify(GATEWAY_UNIT) + ";",
    "const WRAPPED_ACTIONS = " + JSON.stringify(WRAPPED_ACTIONS) + ";",
    'const SHIM_FILE_NAME = ' + JSON.stringify(SHIM_FILE_NAME) + ";",
    'const INSTALL_LINE = "Specstride CLI not found - install it with: ' + installCommand +
      ' (then set SPECSTRIDE_BIN or put it on PATH); specstride-host-hermes doctor reports host.cli-found.";',
    "",
    "const shimDirectory = dirname(fileURLToPath(import.meta.url));",
    "",
    "function isExecutable(path) {",
    "  try {",
    "    if (!statSync(path).isFile()) return false;",
    "    accessSync(path, constants.X_OK);",
    "    return true;",
    "  } catch {",
    "    return false;",
    "  }",
    "}",
    "",
    "// F150-FR-011: the explicit variable, then the search path (this shim's own",
    "// directory excluded), then nothing — never a fetch or an install.",
    "function resolveCli() {",
    "  const explicit = process.env[EXECUTABLE_VARIABLE];",
    "  if (explicit && isExecutable(explicit)) return explicit;",
    "  const entries = (process.env.PATH ?? '').split(':');",
    "  for (const entry of entries) {",
    "    const dir = entry === '' ? '.' : entry;",
    "    if (resolve(dir) === resolve(shimDirectory)) continue;",
    "    const candidate = join(dir, EXECUTABLE_NAME);",
    "    if (isExecutable(candidate)) return candidate;",
    "  }",
    "  return null;",
    "}",
    "",
    "// F150-FR-012: one integer, and only that, is an answer.",
    "function protocolOf(stdout) {",
    "  const text = (stdout ?? '').trim();",
    "  return /^[0-9]+$/.test(text) ? Number(text) : null;",
    "}",
    "",
    "function cgroupFile() {",
    "  return process.env[CGROUP_VARIABLE] ?? " + JSON.stringify(CGROUP_FILE) + ";",
    "}",
    "",
    "function inGatewayCgroup() {",
    "  try {",
    "    return readFileSync(cgroupFile(), 'utf8').includes(GATEWAY_UNIT);",
    "  } catch {",
    "    return false;",
    "  }",
    "}",
    "",
    "function systemdRunPath() {",
    "  for (const entry of (process.env.PATH ?? '').split(':')) {",
    "    const dir = entry === '' ? '.' : entry;",
    "    const candidate = join(dir, 'systemd-run');",
    "    if (isExecutable(candidate)) return candidate;",
    "  }",
    "  return null;",
    "}",
    "",
    "function runUnderSystemdRun(cli, argv) {",
    "  const path = systemdRunPath();",
    "  if (path === null) return null;",
    "  const unit = 'specstride-' + randomBytes(4).toString('hex');",
    "  const asUser = typeof process.getuid === 'function' && process.getuid() !== 0;",
    "  const args = ['--scope', '--collect', '--quiet', '--unit=' + unit];",
    "  if (asUser) args.push('--user');",
    "  args.push('--', cli);",
    "  const result = spawnSync(path, args.concat(argv), { stdio: 'inherit' });",
    "  if (result.error) return { exit: 1, wrapped: false };",
    "  return { exit: result.status ?? 1, wrapped: true };",
    "}",
    "",
    "// F150-FR-014: the watch list, atomic, set semantics.",
    "function recordWatch() {",
    "  try {",
    "    const home = process.env.HERMES_HOME ?? join(process.env.HOME ?? '', '.hermes');",
    "    const directory = join(home, 'specstride-host');",
    "    const file = join(directory, 'watch.json');",
    "    mkdirSync(directory, { recursive: true });",
    "    let known = [];",
    "    try {",
    "      const parsed = JSON.parse(readFileSync(file, 'utf8'));",
    "      if (Array.isArray(parsed)) known = parsed;",
    "    } catch {",
    "      known = [];",
    "    }",
    "    const cwd = process.cwd();",
    "    if (!known.includes(cwd)) known.push(cwd);",
    "    const temporary = file + '.tmp';",
    "    writeFileSync(temporary, JSON.stringify(known, null, 2) + '\\n');",
    "    renameSync(temporary, file);",
    "  } catch {",
    "    // The watch list is host state, never a reason to fail a launch.",
    "  }",
    "}",
    "",
    "const argv = process.argv.slice(2);",
    "const action = argv[0] ?? '';",
    "",
    "const cli = resolveCli();",
    "if (cli === null) {",
    "  console.error(INSTALL_LINE);",
    "  process.exit(127);",
    "}",
    "",
    "const probe = spawnSync(cli, [PROTOCOL_FLAG], { encoding: 'utf8' });",
    "const protocol = protocolOf(probe.stdout);",
    "if (protocol === null || protocol < PROTOCOL_MIN || protocol > PROTOCOL_MAX) {",
    "  console.log(REFUSAL_LINE);",
    "  process.exit(4);",
    "}",
    "",
    "// The gateway-cgroup escape: launch and resume only; status is never wrapped.",
    "if (WRAPPED_ACTIONS.includes(action) && inGatewayCgroup()) {",
    "  const wrapped = runUnderSystemdRun(cli, argv);",
    "  if (wrapped !== null && wrapped.wrapped && wrapped.exit === 0) {",
    "    if (action === 'launch') recordWatch();",
    "    process.exit(0);",
    "  }",
    "  console.error(WARN_LINE);",
    "}",
    "",
    "const direct = spawnSync(cli, argv, { stdio: 'inherit' });",
    "if (action === 'launch' && (direct.status ?? 1) === 0) recordWatch();",
    "process.exit(direct.status ?? 1);",
    "",
  ];
  return lines.join("\n");
}

/**
 * The build-time check that the shim text names itself and nothing else: the
 * built file is `specstride-hermes`, and the build refuses the bare engine
 * name (T015).
 */
export function shimBuildChecks(): void {
  assertShimFileName(SHIM_FILE_NAME);
  if (thisPackageProtocolRange().min !== 1 || thisPackageProtocolRange().max !== 1) {
    throw new Error("this package supports protocol 1 only (package.json#specstride.protocol)");
  }
}
