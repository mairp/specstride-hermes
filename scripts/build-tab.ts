/**
 * The tab bundle build (T062; F151-FR-052; contracts/151-hermes-kanban/
 * tab-manifest.md §Drift): wrap the client sources (with the generated closed
 * sets) in ONE IIFE that registers the tab once under
 * `window.__HERMES_PLUGINS__.register("specstride", …)`, and write
 *
 * - `<out>/index.js`  — the bundle (type-stripped, import-free, no React copy);
 * - `<out>/style.css` — the stylesheet copy.
 *
 * The output root is `SPECSTRIDE_TAB_OUT` when set (the drift test's seam),
 * else `hermes-plugin/specstride/dashboard/dist`. The build is deterministic:
 * the same sources give byte-equal outputs (T065).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";

const ROOT = resolve(join(dirname(fileURLToPath(import.meta.url)), ".."));

/** The client sources, in dependency order (each defines what later ones
 *  import; the bundler strips the `import` lines and keeps the order). */
const SOURCES: readonly string[] = [
  "src/kanban/generated/closed-sets.ts",
  "src/tab/client/tree.ts",
  "src/tab/client/presentation.ts",
  "src/tab/client/window.ts",
  "src/tab/client/board-model.ts",
  "src/tab/client/board-tree.ts",
  "src/tab/client/poller.ts",
  "src/tab/client/react-adapter.ts",
  "src/tab/client/index.ts",
];

const DASH = join(ROOT, "hermes-plugin", "specstride", "dashboard");

/** The bundle of one source: type-stripped, imports removed, `export` removed. */
function moduleBody(relPath: string): string {
  const text = readFileSync(join(ROOT, relPath), "utf8");
  const stripped = stripTypeScriptTypes(text, { mode: "strip" });
  return stripped
    // whole import statements (single- or multi-line), removed — the sources
    // are concatenated in dependency order instead
    .replace(/import\s+[\s\S]*?from\s*["'][^"']+["'];\s*/g, "")
    .replace(/export\s+/g, "")
    .replace(/\n{3,}/g, "\n\n");
}

/** The banner comment of the bundle (deterministic; no clock, no env). */
const BANNER = `/* The dashboard tab bundle of Specstride (feature 151-hermes-kanban).
 * Generated by scripts/build-tab.ts — do not edit by hand. One registration:
 * window.__HERMES_PLUGINS__.register("specstride", …). No React copy: React
 * arrives from window.__HERMES_PLUGIN_SDK__ (the closed SDK set). */
`;

/** The bundle: one IIFE, one registration, no imports. */
export function buildTabBundle(): string {
  const bodies = SOURCES.map(moduleBody).join("\n");
  return `${BANNER}(function () {\n"use strict";\n${bodies}\n})();\n`;
}

/** The stylesheet of the tab, prefixed with its banner. */
export function buildTabStyles(): string {
  return readFileSync(join(ROOT, "src", "tab", "client", "styles.css"), "utf8");
}

/** Build the tab bundle and stylesheet into `outDir`. */
export function buildTab(outDir: string): string[] {
  mkdirSync(outDir, { recursive: true });
  const bundle = join(outDir, "index.js");
  const styles = join(outDir, "style.css");
  writeFileSync(bundle, buildTabBundle());
  writeFileSync(styles, buildTabStyles());
  return [bundle, styles];
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const outRoot = process.env.SPECSTRIDE_TAB_OUT;
  const outDir = outRoot !== undefined && outRoot !== "" ? resolve(outRoot) : join(DASH, "dist");
  for (const path of buildTab(outDir)) console.log("wrote " + path);
}
